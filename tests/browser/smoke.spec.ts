import { test, expect } from '@playwright/test';
test('browser inspection fails closed and home exposes compact monitoring choices and history', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'SignalGuard', exact: true })).toBeVisible();
  await expect(page.getByText('Native monitoring is unavailable.', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: 'START GUARD', exact: true })).toBeDisabled();
  await expect(page.getByRole('tab', { name: /Settings/ })).toHaveCount(0);
  await expect(page.getByRole('switch', { name: 'Internet', exact: true })).toBeVisible();
  await expect(page.getByRole('switch', { name: 'Cellular network', exact: true })).toBeVisible();
  await expect(page.getByRole('switch')).toHaveCount(2);
  await expect(page.getByRole('heading', { name: 'Monitor', exact: true })).toBeVisible();
  const internet = await page.getByRole('switch', { name: 'Internet', exact: true }).boundingBox();
  const cellular = await page.getByRole('switch', { name: 'Cellular network', exact: true }).boundingBox();
  expect(internet).not.toBeNull();
  expect(cellular).not.toBeNull();
  expect(Math.abs(internet!.x - cellular!.x)).toBeLessThanOrEqual(1);
  await expect(page.getByText('Private by design')).toHaveCount(0);
  await expect(page.getByText('Vibration', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Critical alerts', { exact: true })).toHaveCount(0);
  await page.getByRole('switch', { name: 'Cellular network', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Cellular network', exact: true })).not.toBeChecked();
  await expect(page.getByRole('button', { name: 'START GUARD', exact: true })).toBeDisabled();
  await page.getByRole('switch', { name: 'Internet', exact: true }).click();
  await expect(page.getByText('Keep at least one monitoring condition enabled.')).toBeVisible();
  await expect(page.getByRole('switch', { name: 'Internet', exact: true })).toBeChecked();
  await page.getByRole('tab', { name: /History/ }).click();
  await expect(page.getByText('Sample data · UI preview only')).toBeVisible();
  await expect(page.getByText('Brief interruption · no alert')).toBeVisible();
  await expect(page.getByText('Guard interrupted', { exact: true })).toBeVisible();
  await expect(page.getByText('Monitoring resumed', { exact: true })).toBeVisible();
});
test('Spanish route content is complete', async ({ browser }) => {
  const context = await browser.newContext({ locale: 'es-ES', viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:8088');
  await expect(page.getByRole('button', { name: 'INICIAR GUARDIA', exact: true })).toBeDisabled();
  await expect(page.getByRole('tab', { name: /Ajustes/ })).toHaveCount(0);
  await expect(page.getByRole('switch', { name: 'Internet', exact: true })).toBeVisible();
  await expect(page.getByRole('switch', { name: 'Red móvil', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Monitorizar', exact: true })).toBeVisible();
  await expect(page.getByText('Vibración', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Avisos críticos', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('switch')).toHaveCount(2);
  await page.getByRole('tab', { name: /Historial/ }).click();
  await expect(page.getByText('Datos de ejemplo · Solo vista previa')).toBeVisible();
  await expect(page.getByText('Guardia interrumpida', { exact: true })).toBeVisible();
  await expect(page.getByText('Monitorización reanudada', { exact: true })).toBeVisible();
  await context.close();
});
